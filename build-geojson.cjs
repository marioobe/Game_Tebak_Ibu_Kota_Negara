    'Antigua dan Barbuda': [[[-61.9, 17.0], [-61.7, 17.0], [-61.7, 17.2], [-61.9, 17.2], [-61.9, 17.0]]],
    'Tuvalu': [[[179.1, -8.6], [179.3, -8.6], [179.3, -8.4], [179.1, -8.4], [179.1, -8.6]]],
