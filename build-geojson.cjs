// Coordinate rounding to 2 decimal places (~1.1 km precision at equator) for world boundary
function roundCoords(coords) {
    if (typeof coords[0] === 'number') {
        return [Math.round(coords[0] * 100) / 100, Math.round(coords[1] * 100) / 100];
    }
    return coords.map(roundCoords);
}

// Build index of 50m features for missing countries
const feat50Map = new Map();
for (const f of geo50.features) {
    if (f.properties && f.properties.name) {
        feat50Map.set(f.properties.name, f);
    }
}

// Create lookup of 110m features
const feat110Map = new Map();
for (const f of geo110.features) {
    if (f.properties && f.properties.name) {
        feat110Map.set(f.properties.name, f);
    }
}

const finalFeatures = [];
const missingNames = [];

